"""Rollouts per second for the RL rewards, with and without the warm pools (TSAI, 5 Nov: "Measure rollouts per
second with the pool before you change the step size").

Each rollout is one reward() call on a known output: every code task with its reference (scores 1) and a stub
(scores 0), every SWE env with its gold patch (1) and a no-op patch (0). A rollout counts only if it gets the
expected score, so a fast but wrong setup cannot look good.

Modes:
    serial     one container per call, one at a time
    parallel   one container per call, `--workers` calls at once
    pool       warm code pool from pool.py, `--workers` calls at once (code tasks only; SWE envs are not pooled,
               see pool.py)

Usage: python rl/bench_pool.py [--workers 8] [--swe-workers 4] [--repeat 3] [--write ../results/reward_pool_bench.md]
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import platform
import subprocess
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("g10_rl_reward", HERE / "reward.py")
reward = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(reward)
pool = reward._pool()


def jobs(prefix: str, repeat: int) -> list[tuple[str, str, float]]:
    out = []
    for env_id in [i for i in reward.list_envs() if i.startswith(prefix)]:
        good, bad = reward.known_outputs(env_id)
        out += [(env_id, good, 1.0), (env_id, bad, 0.0)] * repeat
    return out


def run(batch, workers: int) -> dict:
    def one(job):
        env_id, output, want = job
        return reward.reward(env_id, output)[0] == want

    t0 = time.monotonic()
    with ThreadPoolExecutor(workers) as ex:
        ok = list(ex.map(one, batch))
    secs = time.monotonic() - t0
    return {"rollouts": len(batch), "correct": sum(ok), "seconds": round(secs, 1),
            "per_second": round(len(batch) / secs, 2)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=8, help="code-task workers (one per CPU core)")
    ap.add_argument("--swe-workers", type=int, default=4, help="SWE workers (each container may use 2 GB)")
    ap.add_argument("--repeat", type=int, default=3, help="code tasks: repeat each good/bad pair this many times")
    ap.add_argument("--write", type=Path)
    args = ap.parse_args()
    code, swe = jobs("code/", args.repeat), jobs("swe/", 1)
    rows = []

    reward.configure()
    rows.append(("code", "serial", 1, run(code[: len(code) // args.repeat], 1)))
    rows.append(("code", "parallel", args.workers, run(code, args.workers)))
    with pool.CodePool(workers=args.workers) as cp:
        reward.configure(code_runner=cp.runner)
        run(code[:args.workers], args.workers)  # warm-up: containers already started; first exec pays imports
        rows.append(("code", "pool", args.workers, run(code, args.workers)))
    reward.configure()
    rows.append(("swe", "serial", 1, run(swe, 1)))
    rows.append(("swe", "parallel", args.swe_workers, run(swe, args.swe_workers)))

    for kind, mode, w, r in rows:
        print(json.dumps({"kind": kind, "mode": mode, "workers": w, **r}))
    if args.write:
        info = subprocess.run(["docker", "info", "-f", "{{.NCPU}} CPUs, {{.MemTotal}} bytes, {{.OperatingSystem}}"],
                              capture_output=True, text=True).stdout.strip()
        lines = [
            "# Reward throughput: with and without the warm pools",
            "",
            f"Generated by `rl/bench_pool.py --workers {args.workers} --swe-workers {args.swe_workers} "
            f"--repeat {args.repeat}` on {time.strftime('%Y-%m-%d %H:%M %Z')}.",
            f"Host: {platform.machine()} {platform.system()}; Docker: {info}.",
            "",
            "A rollout is one `reward(env_id, output)` call on a known output (reference or gold patch must score 1, "
            "a stub or no-op patch must score 0); `correct` counts the ones that did. Code tasks: the 10 tasks in "
            f"`rl/tasks/`, each good/bad pair {args.repeat} times (serial: once). SWE: the 21 envs in `swe-envs/`, "
            "gold and no-op once each.",
            "",
            "| kind | mode | workers | rollouts | correct | seconds | rollouts/s |",
            "|---|---|---|---|---|---|---|",
        ]
        lines += [f"| {k} | {m} | {w} | {r['rollouts']} | {r['correct']} | {r['seconds']} | {r['per_second']} |"
                  for k, m, w, r in rows]
        lines += ["", "Modes: `serial` and `parallel` start one container per call (`docker run --rm`); `pool` uses "
                  "`rl/pool.py`: one reused container per worker, cleaned after every rollout. SWE envs are not pooled: "
                  "reusing a container with a writable repository is unsafe, and pre-started single-use containers "
                  "measured slower than plain parallel `docker run --rm` here (1.59 vs 2.21 rollouts/s in an earlier "
                  "run of this script, 21 envs x gold and no-op, 4 workers)."]
        args.write.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0 if all(r["correct"] == r["rollouts"] for *_, r in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())
