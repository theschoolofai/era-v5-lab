"""Explain any code, cause, alert or Slurm reason in plain words, with what to do next.

In simple words: paste whatever you see (an exit code, a word from an event, an alert id, a drain reason from
`sinfo -R`, a pending reason from `squeue`) and get: what happened, what the system already did, what you do.

    python metrics/explain.py 78                 exit code of a job
    python metrics/explain.py 137                raw exit code of a trainer
    python metrics/explain.py loss_spike         cause field of an event (job.held, checkpoint.failed, ...)
    python metrics/explain.py CK-05              alert / metric id
    python metrics/explain.py v5:xid,ecc_uncorrectable    drain reason (sinfo -R)
    python metrics/explain.py JobHeldUser        Slurm state or pending reason
    python metrics/explain.py --all              everything, as one Markdown page
"""
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
from common.reasons import CAUSES, DRAIN, EXIT_CODES, RAW_EXIT, SLURM  # noqa: E402

CATALOG = os.path.join(HERE, "catalog.yaml")


def _metric(cat, mid):
    for m in cat["metrics"]:
        if m["id"].lower() == mid.lower():
            return m
    return None


def _block(title, meaning, auto, you_do, extra=()):
    lines = [title, f"  What happened : {meaning}", f"  Already done  : {auto}", f"  What you do   : {you_do}"]
    return "\n".join(lines + [f"  {e}" for e in extra])


def explain(word: str, cat: dict) -> str:
    w = word.strip()
    if w.lstrip("-").isdigit():
        n = int(w)
        if n in EXIT_CODES:
            e = EXIT_CODES[n]
            extra = [f"Alert         : {e['alert']}"] if e.get("alert") else []
            return _block(f"Exit {n} = {e['title']} (severity: {e['severity']})", e["meaning"], e["auto"],
                          e["you_do"], extra)
        if n in RAW_EXIT:
            return _block(f"Trainer exit {n}", RAW_EXIT[n],
                          "the job wrapper turned it into 75 (retry); 3 crashes in 30 min turn it into 78 (held)",
                          "nothing for one crash; if it repeats, read the job log")
        if n in (3, 4):
            return _block(f"Health check exit {n} = {'warn' if n == 3 else 'fail'}",
                          "a node health check found a problem (see its JSON report)",
                          "fail in periodic mode: node drained, jobs saved and moved" if n == 4 else "reported only",
                          "read the report's failed/warn checks; explain each name (e.g. explain.py xid)")
        return f"Exit {n}: not one of ours. 0 done, 75 retry, 78 held; 3/4 health warn/fail; 128+N = killed by signal N."
    if w in CAUSES:
        c = CAUSES[w]
        extra = [f"Alert         : {c['alert']}"] if c.get("alert") else []
        return _block(f"Cause '{w}' = {c['title']} (severity: {c['severity']})", c["meaning"], c["auto"],
                      c["you_do"], extra)
    m = _metric(cat, w)
    if m:
        sev = cat["severity"]
        th = ", ".join(f"{k.upper()} {'≥' if m['direction'] == 'above' else '≤'} {m[k]}"
                       for k in ("low", "medium", "high") if m.get(k) is not None)
        return _block(f"{m['id']} {m['name']} ({m['unit']}; {th})", m["why"], "an alert.fired event (and a page "
                      "for HIGH)", m["action"],
                      [f"HIGH response : {sev['high']['response']}; {sev['high']['who']}", f"Owner         : {m['owner']}"])
    names = w[3:] if w.startswith("v5:") else w
    parts = [p for p in names.split(",") if p in DRAIN]
    if parts:
        return "\n\n".join(_block(f"Node drained: {p}", *DRAIN[p]) +
                           "\n  Then          : scontrol update nodename=<node> state=resume (after the fix)"
                           for p in parts)
    if w in SLURM:
        return f"Slurm '{w}': {SLURM[w]}"
    for k, v in {**CAUSES}.items():          # cause with extra text, e.g. "crash_loop(3 in 1800s)"
        if w.startswith(k):
            return explain(k, cat)
    return (f"'{w}' is not listed. Try an exit code (0/75/78), a cause ({', '.join(list(CAUSES)[:5])}, ...), "
            f"an alert id (CK-05), a drain reason (v5:xid) or a Slurm reason (JobHeldUser).")


def all_md(cat) -> str:
    L = ["# Every code, cause and reason, with what to do", "",
         "Generated by `python metrics/explain.py --all` from `common/reasons.py` and `metrics/catalog.yaml`.", "",
         "## Job exit codes", "", "| Code | Means | Already done | You do |", "|---|---|---|---|"]
    L += [f"| {n} {e['title']} | {e['meaning']} | {e['auto']} | {e['you_do']} |" for n, e in EXIT_CODES.items()]
    L += ["", "Raw trainer exit codes (before the wrapper maps them to 75, or 78 after 3 crashes in 30 min):", ""]
    L += [f"- `{n}`: {t}" for n, t in RAW_EXIT.items()]
    L += ["", "## Causes (the `cause` field in events, and the Slurm job comment)", "",
          "| Cause | Severity | Means | Already done | You do | Alert |", "|---|---|---|---|---|---|"]
    L += [f"| `{k}` | {c['severity']} | {c['meaning']} | {c['auto']} | {c['you_do']} | {c.get('alert') or ''} |"
          for k, c in CAUSES.items()]
    L += ["", "## Node drain reasons (`sinfo -R` shows `v5:<names>`)", "",
          "| Reason | Means | Already done | You do |", "|---|---|---|---|"]
    L += [f"| `{k}` | {a} | {b} | {c} |" for k, (a, b, c) in DRAIN.items()]
    L += ["", "After the fix: `scontrol update nodename=<node> state=resume`.", "",
          "## Slurm states and pending reasons", "", "| Shown | Means |", "|---|---|"]
    L += [f"| `{k}` | {v} |" for k, v in SLURM.items()]
    return "\n".join(L) + "\n"


def main(argv):
    cat = yaml.safe_load(open(CATALOG))
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    if argv[0] == "--all":
        out = all_md(cat)
        if len(argv) > 1:
            open(argv[1], "w").write(out)
        else:
            print(out)
        return 0
    print("\n\n".join(explain(w, cat) for w in argv))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
