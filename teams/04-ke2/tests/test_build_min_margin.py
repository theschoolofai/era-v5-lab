def sm(margins, rivals, precision="fp64"):
    n = len(margins)
    return pm.SelfMargins(
        precision,
        token_ids=np.arange(n),
        self_scores=np.ones(n),
        margins=np.array(margins, dtype=np.float64),
        rival_ids=np.array(rivals, dtype=np.int64),
        overlaps=np.ones(n, dtype=np.int64),
    )


def test_display_text_escapes_controls_and_partial_utf8_but_keeps_pipes():
    assert bmm.display_text(b"a|b\n") == "a|b\\x0a"  # CSV keeps the token's own characters
    assert bmm.display_text(b"\xe0\xa4") == "\\xe0\\xa4"
    assert bmm.display_text("नमस्ते".encode()) == "नमस्ते"


def test_class_minima_takes_the_lowest_margin_and_the_lowest_id_on_ties(make_byte_table):
    t = make_byte_table([b"aa", b"ab", b"ac", b"cd", b"q"], P=4)
    rows = bmm.class_minima(["A", "A", "A", "B", "C"], sm([0.2, 0.1, 0.1, 0.3, 0.5], [1, 0, 0, 2, 0]), t)
    assert [(r["script_class"], r["token_id"], r["rival_id"], r["min_margin"]) for r in rows] == [
        ("A", 1, 0, 0.1),
        ("B", 3, 2, 0.3),
        ("C", 4, 0, 0.5),
    ]
    a = rows[0]
    assert list(a) == bmm.CLASS_COLUMNS
    assert (a["n_tokens"], a["rival_class"], a["token_len"], a["n_nonpositive"]) == (3, "A", 2, 0)
    assert a["bf16_steps"] == pytest.approx(0.1 / 2.0**-8)


def test_worst_ids_unions_the_k_lowest_per_class_over_precisions():
    classes = ["A", "A", "A", "B", "B"]
    margins = {
        "fp64": sm([0.5, 0.1, 0.3, 0.2, 0.4], [1] * 5),
        "bf16": sm([0.05, 0.1, 0.3, 0.2, 0.4], [1] * 5, "bf16"),
    }
    assert bmm.worst_ids(classes, margins, k=1).tolist() == [0, 1, 3]


def test_single_token_class_takes_its_rival_from_the_whole_vocabulary(make_byte_table):
    t = make_byte_table([b"abc", b"abd", b"zz"], P=4)
    class_rows, _, _ = bmm.run(t, ["Solo", "Latin", "Latin"], worst_k=1)
    solo = next(r for r in class_rows if r["precision"] == "fp64" and r["script_class"] == "Solo")
    assert (solo["n_tokens"], solo["rival_id"], solo["rival_class"]) == (1, 1, "Latin")


def test_run_writes_four_consistent_outputs(synthetic_p8, tmp_path):
    classes = ["A" if i % 3 else "B" for i in range(synthetic_p8.vocab_size)]
    class_rows, dense_rows, summary = bmm.run(synthetic_p8, classes, worst_k=2, chunk_rows=16)
    bmm.write_outputs(tmp_path, class_rows, dense_rows, summary)
    assert {p.name for p in tmp_path.iterdir()} == {
        "min_margin_by_class_P8.csv",
        "dense_check_P8.csv",
        "summary_P8.json",
        "min_margin_P8.md",
    }
    with open(tmp_path / "min_margin_by_class_P8.csv") as f:
        rows = list(csv.DictReader(f))
    assert list(rows[0]) == bmm.CLASS_COLUMNS
    assert {(r["precision"], r["script_class"]) for r in rows} == {(p, c) for p in pm.PRECISIONS for c in "AB"}
    with open(tmp_path / "dense_check_P8.csv") as f:
        assert {r["mode"] for r in csv.DictReader(f)} == set(dc.MODES)
    assert summary["gate_all_positive"] is True and summary["exhaustive"] is True
    assert set(summary["precisions"]) == set(pm.PRECISIONS) and set(summary["dense"]) == set(dc.MODES)
    assert summary["precisions"]["fp64"]["max_abs_delta_vs_fp64"] == 0.0
    md = (tmp_path / "min_margin_P8.md").read_text()
    assert md.startswith("<!-- generated by src/margins/build_min_margin.py") and "| A |" in md and "bf16_out" in md


